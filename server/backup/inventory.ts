export type ColumnKind = 'uuid' | 'text' | 'date' | 'timestamptz' | 'numeric' | 'int' | 'bool' | 'json' | 'bytea'

export type BackupClass = 'canonical' | 'derived' | 'operational'

export type BackupColumn = {
  name: string
  kind: ColumnKind
}

export type BackupReference = {
  column: string
  table: string
}

export type BackupTable = {
  name: string
  backupClass: BackupClass
  primaryKey: readonly string[]
  columns: readonly BackupColumn[]
  references: readonly BackupReference[]
  /** Migration seed rows. A new database already has these, with different UUIDs. */
  seeded: boolean
  /** Included in the Settings portable download. */
  portable: boolean
}

const NEVER_EXPORT_TABLES = [
  'user',
  'session',
  'account',
  'verification',
  'jwks',
  'schema_migrations',
] as const

export const AUTH_TABLES_EXCLUDED: readonly string[] = NEVER_EXPORT_TABLES

function col(name: string, kind: ColumnKind): BackupColumn {
  return { name, kind }
}

function table(definition: BackupTable): BackupTable {
  if ((NEVER_EXPORT_TABLES as readonly string[]).includes(definition.name)) {
    throw new Error(`Refusing to export ${definition.name}`)
  }
  return definition
}

