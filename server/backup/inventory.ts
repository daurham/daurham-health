export function backupTable(name: string): BackupTable | undefined {
  return BACKUP_TABLES.find((item) => item.name === name)
}

export function tablesForProfile(profile: 'full' | 'portable'): readonly BackupTable[] {
  if (profile === 'full') {
    return BACKUP_TABLES
  }
  return BACKUP_TABLES.filter((item) => item.portable)
}
